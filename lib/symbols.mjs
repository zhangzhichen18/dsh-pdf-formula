// ---------------------------------------------------------------- families
//
// Recognition works on outline shape, and Unicode encodes many codepoints that
// share one shape (a whole mathematical-alphabet family per letter, several
// bracket and integral variants, U+2212 vs hyphen, ...).  A family groups those
// codepoints so a match can be resolved to the canonical member instead of an
// arbitrary stylistic sibling.

/** latin ranges that are math-alphanumeric variants of ASCII letters/digits */
function mathAlnumBase(cp) {
  const blocks = [
    [0x1d400, 0x1d433, 'latin'], [0x1d434, 0x1d467, 'latin'],
    [0x1d468, 0x1d49b, 'latin'], [0x1d49c, 0x1d4cf, 'latin'],
    [0x1d4d0, 0x1d503, 'latin'], [0x1d504, 0x1d537, 'latin'],
    [0x1d538, 0x1d56b, 'latin'], [0x1d56c, 0x1d59f, 'latin'],
    [0x1d5a0, 0x1d5d3, 'latin'], [0x1d5d4, 0x1d607, 'latin'],
    [0x1d608, 0x1d63b, 'latin'], [0x1d63c, 0x1d66f, 'latin'],
    [0x1d670, 0x1d6a3, 'latin'],
    [0x1d6a8, 0x1d6e1, 'greek'], [0x1d6e2, 0x1d71b, 'greek'],
    [0x1d71c, 0x1d755, 'greek'], [0x1d756, 0x1d78f, 'greek'],
    [0x1d790, 0x1d7c9, 'greek'], [0x1d7ca, 0x1d7cb, 'greek'],
  ];
  for (const [a, b, kind] of blocks) {
    if (cp >= a && cp <= b) {
      const i = (cp - a) % (kind === 'latin' ? 52 : 58);
      if (kind === 'latin') return i < 26 ? 0x41 + i : 0x61 + (i - 26);
      // Greek capitals run 0x391.. and lowercase 0x3b1..; the block is laid out
      // capitals-first in chunks of 25/33 depending on style, so map by position
      // in the canonical Greek order instead of by arithmetic.
      const order = GREEK_ORDER;
      return order[i % order.length];
    }
  }
  const digitBlocks = [[0x1d7ce, 0x1d7ff]];
  for (const [a] of digitBlocks) if (cp >= a && cp <= a + 49) return 0x30 + ((cp - a) % 10);
  return null;
}

