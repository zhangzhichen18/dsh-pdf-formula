/** Canonical id for the shape family of a codepoint. */
export function familyOf(cp) {
  if (FAMILY_ALIASES.has(cp)) return FAMILY_ALIASES.get(cp);
  const base = mathAlnumBase(cp);
  if (base !== null) return base;
  // bracket and integral extensions collapse onto their base character
  if (cp >= 0x239b && cp <= 0x23ad) {
    const map = { 0x239b: 0x0028, 0x239c: 0x0028, 0x239d: 0x0028, 0x239e: 0x0029, 0x239f: 0x0029, 0x23a0: 0x0029, 0x23a1: 0x005b, 0x23a2: 0x005b, 0x23a3: 0x005b, 0x23a4: 0x005d, 0x23a5: 0x005d, 0x23a6: 0x005d, 0x23a7: 0x007b, 0x23a8: 0x007b, 0x23a9: 0x007b, 0x23aa: 0x007c, 0x23ab: 0x007d, 0x23ac: 0x007d, 0x23ad: 0x007d };
    return map[cp] ?? cp;
  }
  if (cp >= 0x27e6 && cp <= 0x27ef) return 0x005b;
  if (cp === 0x27e8 || cp === 0x27e9 || cp === 0x3008 || cp === 0x3009) return 0x27e8;
  if (cp >= 0x2a00 && cp <= 0x2aff) {
    // n-ary and large-operator variants resolve to their base operator
    const map = { 0x2a00: 0x2a00, 0x2a01: 0x2a00, 0x2a02: 0x2a02, 0x2a03: 0x2a02, 0x2a04: 0x2a04, 0x2a05: 0x2a05, 0x2a06: 0x2a06, 0x2a09: 0x00d7, 0x2a0b: 0x222b, 0x2a0c: 0x222b, 0x2a0d: 0x222b, 0x2a0e: 0x222b, 0x2a0f: 0x222b, 0x2a10: 0x222b, 0x2a11: 0x222b, 0x2a12: 0x222b, 0x2a15: 0x222b, 0x2a16: 0x222b, 0x2a17: 0x222b, 0x2a18: 0x222b, 0x2a19: 0x222b, 0x2a1a: 0x222b, 0x2a1b: 0x222b, 0x2a1c: 0x222b, 0x2a2f: 0x00d7 };
    return map[cp] ?? cp;
  }
  if (cp >= 0x2a7d && cp <= 0x2a7e) return 0x2264;
  if (cp >= 0x2a7f && cp <= 0x2a80) return 0x003c;
  if (cp >= 0x2a81 && cp <= 0x2a82) return 0x003e;
  if (cp >= 0x2a83 && cp <= 0x2a84) return 0x2265;
  if (cp === 0x2b1d) return 0x2669;
  if (cp >= 0x2b05 && cp <= 0x2b07) return 0x2b05;
  if (cp === 0x21d2) return 0x21d2;
  if (cp === 0x21d4) return 0x21d4;
  if (cp === 0x21d0) return 0x21d0;
  if (cp === 0x21d1) return 0x21d1;
  if (cp === 0x21d3) return 0x21d3;
  if (cp === 0x22a4) return 0x22a4;
  if (cp === 0x22a5) return 0x22a5;
  if (cp >= 0x2900 && cp <= 0x297f) return cp; // distinct arrows stay distinct
  return cp;
}

